import sqlite3
conn = sqlite3.connect('financas.db')
c = conn.cursor()
c.execute("CREATE TABLE categorias (id INTEGER PRIMARY KEY, nome TEXT, tipo TEXT, macro_categoria TEXT)")
c.execute("CREATE TABLE lancamentos (id INTEGER PRIMARY KEY, data TEXT, mes INTEGER, ano INTEGER, tipo TEXT, categoria TEXT, descricao TEXT, valor REAL, forma_pgto TEXT, observacao TEXT, competencia TEXT)")
c.execute("CREATE TABLE orcamento (macro_categoria TEXT, ano INTEGER, mes INTEGER, valor_orcado REAL, PRIMARY KEY (macro_categoria, ano, mes))")
c.execute("CREATE TABLE investimentos (id INTEGER PRIMARY KEY, ativo TEXT, classe TEXT, saldo_inicial REAL, saldo_atual REAL, rentabilidade_pct REAL)")
c.execute("CREATE TABLE dividas (id INTEGER PRIMARY KEY, credor TEXT, tipo TEXT, saldo_devedor REAL, taxa_juros_mes REAL, parcela_min REAL, parcelas_rest INTEGER)")
c.execute("CREATE TABLE metas (id INTEGER PRIMARY KEY, nome TEXT, prazo TEXT, valor_alvo REAL, valor_atual REAL)")
